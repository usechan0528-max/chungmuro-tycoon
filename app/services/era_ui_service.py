def era_ui_profile(year: int | None) -> dict[str, Any]:
    key = _era_key(year or 2026)
    profile = dict(ERA_UI_PROFILES[key])
    profile["id"] = key
    profile["year"] = int(year or 2026)
    return profile


def _era_key(year: int) -> str:
    if year < 1990:
        return "1980s"
    if year < 2000:
        return "1990s"
    if year < 2010:
        return "2000s"
    if year < 2020:
        return "2010s"
    return "2020s"
